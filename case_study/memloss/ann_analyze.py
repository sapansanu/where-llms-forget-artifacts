"""Summarize the Section 7 retrieval experiment (memloss.ann).

Per configuration: gold-paragraph hits at k=5, overlap with the exact list, exact match, and the rows correct with
the exact list but wrong with the approximate one (C->W). For C->W rows whose approximate list lost a gold paragraph,
the repair rates of protection (lost gold put back) and the count-matched sham, with Wilson intervals and McNemar's
test on the paired outcomes.

    python -m memloss.ann_analyze results/ann/ann-n500.jsonl --out results/final/ann
"""

import argparse
import json

import pandas as pd
from scipy.stats import binomtest

from memloss.analyze import wilson


def summarize(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for cfg, g in df.groupby("config", sort=False):
        cw = g[g["exact_correct"] & ~g["correct"]]
        wc = g[~g["exact_correct"] & g["correct"]]
        lost = cw[cw["protect_correct"].notna()] if "protect_correct" in g else cw.iloc[0:0]
        rec = {"config": cfg, "n": len(g), "em": g["correct"].mean(),
               "gold_hit_rate": g["gold_hits"].sum() / g["gold"].map(len).sum(),
               "both_gold": (g["gold_hits"] == g["gold"].map(len)).mean(),
               "overlap_exact": g["overlap_exact"].mean() / 5, "c_to_w": len(cw), "w_to_c": len(wc),
               "c_to_w_lost_gold": len(lost)}
        if len(lost):
            p, s = lost["protect_correct"].astype(bool), lost["sham_correct"].astype(bool)
            rec.update(protect_repair=p.mean(), sham_repair=s.mean(),
                       protect_ci=wilson(p.sum(), len(p)), sham_ci=wilson(s.sum(), len(s)))
            b, c = int((p & ~s).sum()), int((~p & s).sum())
            rec["mcnemar_p"] = binomtest(b, b + c, 0.5).pvalue if b + c else 1.0
        rows.append(rec)
    return pd.DataFrame(rows)


NAMES = {"exact": "Exact search", "hnsw-8": "HNSW, ef 8", "hnsw-16": "HNSW, ef 16", "hnsw-64": "HNSW, ef 64",
         "pq-8": "Quantized, 8 B", "pq-16": "Quantized, 16 B", "pq-48": "Quantized, 48 B",
         "opq-48": "Rotated, 48 B", "lsh-384": "Sign bits, 48 B"}
ORDER = list(NAMES)


def paper_table(t: pd.DataFrame, n: int, n_paras: int) -> str:
    """The Section 7 table, written from the logged runs so no number is copied by hand."""
    rows = []
    for _, r in t.iterrows():
        rep = "--" if pd.isna(r.get("protect_repair")) else f"{100 * r.protect_repair:.0f} / {100 * r.sham_repair:.0f}"
        cw = "--" if r.config == "exact" else f"{int(r.c_to_w)} ({int(r.c_to_w_lost_gold)})"
        rows.append(f"{NAMES[r.config]} & {100 * r.gold_hit_rate:.0f} & {100 * r.em:.1f} & {cw} & {rep} \\\\")
        if r.config in ("exact", "hnsw-64", "pq-16"):
            rows.append("\\midrule")
    return "\n".join([
        "% Generated by experiments/memloss/ann_analyze.py from the logged runs. Do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Retrieval experiment (Section~\\ref{sec:ann-exp}): " + f"{n} HotpotQA questions over {n_paras:,} "
        "paragraphs, $k=5$, Qwen2.5-7B-Instruct reader. Gold: share of gold paragraphs retrieved (\\%). EM: exact "
        "match (\\%). C$\\to$W: questions correct with exact search and wrong here (in parentheses, those whose list "
        "lost a gold paragraph). Repaired: share of those rows repaired by putting the lost gold paragraphs back "
        "(prot.) or the same number of lost non-gold paragraphs (sham), at the same $k$ (\\%). Codes: bytes per "
        "384-dimensional vector (1,536~B as floats). Quantized: product quantization; rotated: product quantization "
        "after a learned rotation (OPQ); sign bits: those of 384 random projections. HNSW: hierarchical navigable "
        "small-world graph, searched with beam width ef.}",
        "\\label{tab:ann}", "\\footnotesize", "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{@{}lcccc@{}}", "\\toprule",
        "Index & Gold & EM & C$\\to$W (lost gold) & Repaired: prot.\\,/\\,sham \\\\", "\\midrule", *rows,
        "\\bottomrule", "\\end{tabular}", "\\end{table}", ""])


def equal_budget(df: pd.DataFrame, codes=("pq-48", "opq-48", "lsh-384")) -> dict:
    """Paired tests between codes of the same size: gold recall per gold paragraph and exact match per question."""
    have = [c for c in codes if c in set(df["config"])]
    hit = {(r.config, r.id, g): g in r.retrieved for r in df.itertuples() if r.config in have for g in r.gold}
    items = sorted({(i, g) for (_, i, g) in hit})
    em = df[df["config"].isin(have)].pivot(index="id", columns="config", values="correct")
    out = {}
    for i, a in enumerate(have):
        for b in have[i + 1:]:
            x, y = [hit[(a, *it)] for it in items], [hit[(b, *it)] for it in items]
            n10, n01 = sum(p and not q for p, q in zip(x, y)), sum(q and not p for p, q in zip(x, y))
            e10 = int((em[a].astype(bool) & ~em[b].astype(bool)).sum())
            e01 = int((~em[a].astype(bool) & em[b].astype(bool)).sum())
            out[f"{a} vs {b}"] = {"gold_recall": [sum(x) / len(x), sum(y) / len(y)],
                                  "gold_p": binomtest(n10, n10 + n01, 0.5).pvalue if n10 + n01 else 1.0,
                                  "em": [float(em[a].mean()), float(em[b].mean())],
                                  "em_p": binomtest(e10, e10 + e01, 0.5).pvalue if e10 + e01 else 1.0}
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("paths", nargs="+", help="logged runs; configs repeated across runs are taken from the first")
    ap.add_argument("--out", required=True)
    ap.add_argument("--tex", help="also write the paper table here")
    ap.add_argument("--n-paras", type=int, default=66635, help="paragraphs in the index (printed by memloss.ann)")
    args = ap.parse_args()
    df = pd.concat([pd.DataFrame(json.loads(line) for line in open(p)).assign(run=i) for i, p in enumerate(args.paths)])
    first = df.groupby("config")["run"].transform("min")
    df = df[df["run"] == first].drop(columns="run").reset_index(drop=True)
    df["order"] = df["config"].map({c: i for i, c in enumerate(ORDER)})
    df = df.sort_values(["order"], kind="stable").drop(columns="order")
    for c in ("protect_correct", "sham_correct"):
        if c not in df:
            df[c] = None
    t = summarize(df)
    t.to_csv(f"{args.out}_summary.csv", index=False)
    if args.tex:
        with open(args.tex, "w") as f:
            f.write(paper_table(t, df["id"].nunique(), args.n_paras))
    pooled = {}
    for family in ("hnsw", "pq"):
        g = df[df["config"].str.startswith(family) & df["protect_correct"].notna()]
        if len(g):
            p, s = g["protect_correct"].astype(bool), g["sham_correct"].astype(bool)
            b, c = int((p & ~s).sum()), int((~p & s).sum())
            pooled[family] = {"n": len(g), "protect_repair": p.mean(), "sham_repair": s.mean(),
                              "protect_ci": wilson(p.sum(), len(g)), "sham_ci": wilson(s.sum(), len(g)),
                              "mcnemar_p": binomtest(b, b + c, 0.5).pvalue if b + c else 1.0}
    with open(f"{args.out}_stats.json", "w") as f:
        json.dump({"pooled": pooled, "equal_budget": equal_budget(df)}, f, indent=1, default=float)
    pd.set_option("display.width", 200)
    print(t.drop(columns=[c for c in ("protect_ci", "sham_ci") if c in t]).round(3).to_string(index=False))
    print(json.dumps(pooled, indent=1, default=lambda x: round(float(x), 4)))


if __name__ == "__main__":
    main()
