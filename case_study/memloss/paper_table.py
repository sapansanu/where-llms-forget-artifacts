"""Write the case-study table for the paper (tex/tables/case_study.tex) from the logged runs, so no number is copied
by hand. Accuracy as run and with the answer-bearing item protected at the same budget, per policy, budget and
query-knowledge class, with the term the repaired loss is assigned to under the paper's rules 1 and 5.

    uv run python -m memloss.paper_table --out ../tex/tables/case_study.tex
"""

import argparse
import glob

from memloss.analyze import load

NAMES = {"snapkv": "SnapKV", "tova": "TOVA", "streaming": "StreamingLLM"}


def qk_class(press: str, qk: str) -> str:
    """Write-time query knowledge in the paper's labels. StreamingLLM ignores content, so it is query-agnostic even
    when the question is in the context; SnapKV's window and TOVA's last token are a proxy for the query unless the
    question itself is in the context."""
    if press == "streaming":
        return "QG"
    return "QA" if qk == "aware" else "PQ"


def accuracies(df):
    full = df[(df["press"] == "full")].groupby("qk")["correct"].mean()
    comp = df[df["press"] != "full"].copy()
    comp["mode"] = comp.apply(lambda r: "prot" if r.protected else ("sham" if r.sham else "run"), axis=1)
    return full, comp.groupby(["press", "ratio", "qk", "mode"])["correct"].mean()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    g = lambda pat: sorted(glob.glob(f"{args.results}/{pat}"))
    a = load(g("v2/v2-A-*.jsonl") + g("v2/v2-protect-A-*.jsonl") + g("v2/v2-sham-A-*.jsonl"))
    b = load(g("full/B-*.jsonl") + g("full/protect-B-*.jsonl") + g("full/sham-B-*.jsonl"))
    b = b[b["item"] == "answer"]
    (fa, ca), (fb, cb) = accuracies(a), accuracies(b)
    pct = lambda x: f"{100 * x:.0f}"
    rows = [f"Full cache & -- & -- & {pct(fa['agnostic'])} & -- & -- & {pct(fb['agnostic'])} & -- & -- & -- \\\\",
            f"Full cache$^q$ & -- & -- & {pct(fa['aware'])} & -- & -- & {pct(fb['aware'])} & -- & -- & -- \\\\",
            "\\midrule"]
    for press in ("snapkv", "tova", "streaming"):
        for ratio in (0.75, 0.9):
            for qk in ("agnostic", "aware"):
                cls = qk_class(press, qk)
                term = "A (M)" if cls == "QA" else "U (C, A)"
                name = f"{NAMES[press]}" + ("$^q$" if qk == "aware" else "")
                cells = [pct(c[(press, ratio, qk, m)]) for c in (ca, cb) for m in ("run", "sham", "prot")]
                rows.append((f"{name} & {1 - ratio:.0%} & {cls} & " + " & ".join(cells) + f" & {term} \\\\").replace("%", "\\%"))
    n_a = int((a["press"] == "full").sum() / 2)
    n_b = int((b["press"] == "full").sum() / 2)
    tex = "\n".join([
        "% Generated by experiments/memloss/paper_table.py from the logged runs. Do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Case study (Qwen2.5-7B-Instruct): accuracy (\\%) as run, with a random equal-length non-answer span "
        "protected (sham), and with the answer-bearing item $i^*$ protected (prot.), all at the same budget. "
        f"Task~1: {n_a} queries per row; Task~2: exact match on {n_b} queries per row. Keep: share of the context cache "
        "retained. QK: the run's query knowledge (QA query-aware, PQ proxy-query, QG query-agnostic). Term: the loss "
        "that protection repairs, under rule~1 (Section~\\ref{sec:primer-terms}); A (M): Addressing, measured; U (C, A): "
        "Unassigned between Capacity and Addressing. $^q$: the question is also in the context before compression.}",
        "\\label{tab:case}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{1.9pt}",
        "\\begin{tabular}{@{}lccccccccc@{}}",
        "\\toprule",
        " & & & \\multicolumn{3}{c}{Task 1} & \\multicolumn{3}{c}{Task 2} & \\\\",
        "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
        "Policy & Keep & QK & run & sham & prot. & run & sham & prot. & Term \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ])
    with open(args.out, "w") as f:
        f.write(tex)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
